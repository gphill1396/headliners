"""
Build the game's art from the sprite scripts (SPEC S4.2).

    python3 art/build.py            # writes src/render/art.ts
    python3 art/build.py --sheet out.png   # also a contact sheet for review

Needs numpy, scipy and Pillow. The game only reads the generated art.ts.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'sprites'))

from PIL import Image, ImageDraw  # noqa: E402

import monsters  # noqa: E402
import units  # noqa: E402
import portraits  # noqa: E402
from pixelkit import to_sprite  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def all_sprites():
    out = {}
    for name in monsters.SPRITES:
        out[name] = monsters.frames(name)
    for name in units.SPRITES:
        out[f'unit:{name}'] = units.frames(name)
    for name in portraits.PORTRAITS:
        out[f'portrait:{name}'] = portraits.frames(name)
    return out


def write_ts(sprites):
    lines = [
        '/**',
        ' * Generated by art/build.py from the sprite scripts in art/sprites/. Do not edit by hand.',
        ' * Palette-indexed pixel art at the Metroid Fusion bar (SPEC S4.2): two frames each.',
        ' */',
        "import type { AnimSprite } from './portraits';",
        '',
        'export const ART: Record<string, AnimSprite> = {',
    ]
    for name, frames in sprites.items():
        s = to_sprite(frames)
        lines.append(f"  '{name}': {{")
        lines.append('    colors: ' + json.dumps(s['colors'], sort_keys=True).replace('"', "'") + ',')
        lines.append('    frames: [')
        for rows in s['frames']:
            lines.append('      [')
            for r in rows:
                lines.append(f"        '{r}',")
            lines.append('      ],')
        lines.append('    ],')
        lines.append('  },')
    lines.append('};')
    with open(os.path.join(ROOT, 'src', 'render', 'art.ts'), 'w') as fh:
        fh.write('\n'.join(lines) + '\n')


def sheet(sprites, path, scale=5, only=None):
    cells = []
    for name, frames in sprites.items():
        if only and not name.startswith(only):
            continue
        for i, f in enumerate(frames):
            cells.append((f'{name}:{i}', f))
    cw = max(f.shape[1] for _, f in cells) * scale + 16
    ch = max(f.shape[0] for _, f in cells) * scale + 28
    cols = 8 if only else 6
    rows = (len(cells) + cols - 1) // cols
    img = Image.new('RGBA', (cols * cw, rows * ch), (33, 25, 52, 255))
    d = ImageDraw.Draw(img)
    for k, (label, f) in enumerate(cells):
        ox, oy = (k % cols) * cw + 8, (k // cols) * ch + 20
        d.text((ox, oy - 16), label, fill=(240, 230, 210, 255))
        for y in range(f.shape[0]):
            for x in range(f.shape[1]):
                if f[y, x]:
                    h = f[y, x].lstrip('#')
                    d.rectangle([ox + x * scale, oy + y * scale, ox + (x + 1) * scale - 1, oy + (y + 1) * scale - 1], fill=(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255))
    img.save(path)


if __name__ == '__main__':
    sprites = all_sprites()
    write_ts(sprites)
    if '--sheet' in sys.argv:
        only = sys.argv[sys.argv.index('--only') + 1] if '--only' in sys.argv else None
        sheet(sprites, sys.argv[sys.argv.index('--sheet') + 1], scale=8 if only else 5, only=only)
    print(f'{len(sprites)} sprites')
